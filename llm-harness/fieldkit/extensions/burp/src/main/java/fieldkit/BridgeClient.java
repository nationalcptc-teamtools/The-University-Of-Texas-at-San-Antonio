package fieldkit;

import java.io.IOException;
import java.io.InputStream;
import java.io.ByteArrayOutputStream;
import java.net.URI;
import java.net.http.HttpClient;
import java.net.http.HttpRequest;
import java.net.http.HttpResponse;
import java.nio.charset.StandardCharsets;
import java.nio.ByteBuffer;
import java.nio.file.Files;
import java.nio.file.LinkOption;
import java.nio.file.Path;
import java.nio.file.attribute.PosixFilePermission;
import java.time.Duration;
import java.time.Instant;
import java.util.Properties;
import java.util.List;
import java.util.concurrent.CompletableFuture;
import java.util.concurrent.CompletionStage;
import java.util.concurrent.ExecutionException;
import java.util.concurrent.Flow;
import java.util.concurrent.TimeUnit;
import java.util.concurrent.TimeoutException;

/** Sends bounded captures only to the private loopback receiver generated by Fieldkit. */
public final class BridgeClient {
    private BridgeClient() {}

    public record Configuration(URI endpoint, String token, long expires, int maxBytes, int maxEntries) {
        public static Configuration load(Path file) throws IOException {
            if (!Files.isRegularFile(file, LinkOption.NOFOLLOW_LINKS) || Files.size(file) > 4096) {
                throw new IOException("Select a regular private Fieldkit configuration file");
            }
            try {
                for (PosixFilePermission permission : Files.getPosixFilePermissions(file)) {
                    if (permission.name().startsWith("GROUP_") || permission.name().startsWith("OTHERS_")) {
                        throw new IOException("Fieldkit configuration must have owner-only permissions");
                    }
                }
            } catch (UnsupportedOperationException ignored) {
                // Windows filesystems do not expose POSIX permissions.
            }
            Properties values = new Properties();
            try (InputStream stream = Files.newInputStream(file)) { values.load(stream); }
            try {
                URI endpoint = URI.create(values.getProperty("endpoint", ""));
                String token = values.getProperty("token", "");
                long expires = Long.parseLong(values.getProperty("expires_epoch", "0"));
                int maxBytes = Integer.parseInt(values.getProperty("max_bytes", "0"));
                int maxEntries = Integer.parseInt(values.getProperty("max_entries", "0"));
                if (!"1".equals(values.getProperty("schema_version"))
                        || !"http".equals(endpoint.getScheme()) || !"127.0.0.1".equals(endpoint.getHost())
                        || endpoint.getPort() < 1 || endpoint.getPort() > 65535
                        || endpoint.getUserInfo() != null || endpoint.getQuery() != null
                        || endpoint.getFragment() != null || !"/capture".equals(endpoint.getPath())
                        || !token.matches("[a-f0-9]{64}") || expires <= Instant.now().getEpochSecond()
                        || maxBytes < 1 || maxBytes > 16777216 || maxEntries < 1 || maxEntries > 50) {
                    throw new IOException("Configuration is invalid or its receiver has expired");
                }
                return new Configuration(endpoint, token, expires, maxBytes, maxEntries);
            } catch (IllegalArgumentException error) {
                throw new IOException("Configuration is invalid or its receiver has expired");
            }
        }
    }

    public static String send(Configuration configuration, String capture)
            throws IOException, InterruptedException {
        byte[] body = capture.getBytes(StandardCharsets.UTF_8);
        if (body.length > configuration.maxBytes() || configuration.expires() <= Instant.now().getEpochSecond()) {
            throw new IOException("Capture exceeds receiver limits or configuration has expired");
        }
        HttpClient client = HttpClient.newBuilder().connectTimeout(Duration.ofSeconds(5))
                .followRedirects(HttpClient.Redirect.NEVER)
                .proxy(new java.net.ProxySelector() {
                    @Override public java.util.List<java.net.Proxy> select(URI uri) {
                        return java.util.List.of(java.net.Proxy.NO_PROXY);
                    }
                    @Override public void connectFailed(URI uri, java.net.SocketAddress address, IOException error) {}
                }).build();
        HttpRequest request = HttpRequest.newBuilder(configuration.endpoint()).timeout(Duration.ofSeconds(15))
                .header("Authorization", "Bearer " + configuration.token()).header("Content-Type", "application/json")
                .POST(HttpRequest.BodyPublishers.ofByteArray(body)).build();
        CompletableFuture<HttpResponse<byte[]>> pending = client.sendAsync(request,
                information -> new BoundedResponse());
        try {
            HttpResponse<byte[]> response = pending.get(15, TimeUnit.SECONDS);
            if (response.statusCode() != 200) {
                throw new IOException("Fieldkit rejected capture (HTTP " + response.statusCode() + ")");
            }
            return new String(response.body(), StandardCharsets.UTF_8);
        } catch (ExecutionException | TimeoutException error) {
            throw new IOException("Fieldkit response failed or exceeded its limits");
        } finally {
            pending.cancel(true);
        }
    }

    /** Keep a body-wide deadline and byte cap, including chunked/slow replies. */
    private static final class BoundedResponse implements HttpResponse.BodySubscriber<byte[]> {
        private final CompletableFuture<byte[]> body = new CompletableFuture<>();
        private final ByteArrayOutputStream output = new ByteArrayOutputStream();
        private Flow.Subscription subscription;
        @Override public CompletionStage<byte[]> getBody() { return body; }
        @Override public void onSubscribe(Flow.Subscription selected) {
            subscription = selected;
            subscription.request(1);
        }
        @Override public void onNext(List<ByteBuffer> buffers) {
            for (ByteBuffer buffer : buffers) {
                if (buffer.remaining() > 16384 - output.size()) {
                    subscription.cancel();
                    body.completeExceptionally(new IOException("Response byte limit"));
                    return;
                }
                byte[] bytes = new byte[buffer.remaining()];
                buffer.get(bytes); output.writeBytes(bytes);
            }
            subscription.request(1);
        }
        @Override public void onError(Throwable error) { body.completeExceptionally(error); }
        @Override public void onComplete() { body.complete(output.toByteArray()); }
    }

    public static String quote(String text) {
        StringBuilder output = new StringBuilder("\"");
        for (int index = 0; index < text.length(); index++) {
            char character = text.charAt(index);
            switch (character) {
                case '"' -> output.append("\\\"");
                case '\\' -> output.append("\\\\");
                case '\n' -> output.append("\\n");
                case '\r' -> output.append("\\r");
                case '\t' -> output.append("\\t");
                default -> {
                    if (character < 32) output.append(String.format("\\u%04x", (int) character));
                    else output.append(character);
                }
            }
        }
        return output.append('"').toString();
    }
}
